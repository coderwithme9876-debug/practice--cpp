// Convert Character Value to Corresponding ASCII Value

#include <iostream>
using namespace std;
int main()
{

  char c = 'c';
  cout << "the corresponding ASCII value of 'c':";
  cout << int(c) << endl;

  c = 'd';
  cout << "the corresponding ASCII value of 'd': ";
  cout << int(c);
  return 0;
}